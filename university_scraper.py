import requests
from bs4 import BeautifulSoup
import pandas as pd

universities = []
courses = []

university_id = 1
course_id = 1

headers = {"User-Agent": "Mozilla/5.0"}

wiki_urls = [
    "https://en.wikipedia.org/wiki/University_of_Oxford",
    "https://en.wikipedia.org/wiki/University_of_Cambridge",
    "https://en.wikipedia.org/wiki/Harvard_University",
    "https://en.wikipedia.org/wiki/Stanford_University",
    "https://en.wikipedia.org/wiki/University_of_Toronto"
]

for url in wiki_urls:
    response = requests.get(url, headers=headers)
    soup = BeautifulSoup(response.text, "html.parser")

    name = soup.find("h1").get_text()

    infobox = soup.find("table", {"class": "infobox"})
    rows = infobox.find_all("tr")

    city = "Not Available"
    country = "Not Available"
    website = "Not Available"

    for row in rows:
        header = row.find("th")
        data = row.find("td")

        if header and data:
            header_text = header.get_text()

            if "Location" in header_text:
                location_text = data.get_text(strip=True)
                location_parts = location_text.split(",")
                if len(location_parts) >= 2:
                    city = location_parts[0]
                    country = location_parts[1]

            if "Website" in header_text:
                website = data.get_text(strip=True)

    universities.append({
        "university_id": university_id,
        "university_name": name,
        "country": country,
        "city": city,
        "website": website
    })

    # Add 5 dummy courses (still structured properly)
    sample_courses = ["Engineering", "Medicine", "Law", "Business", "Computer Science"]

    for course in sample_courses:
        courses.append({
            "course_id": course_id,
            "university_id": university_id,
            "course_name": course,
            "level": "Bachelor's",
            "discipline": course,
            "duration": "Not Available",
            "fees": "Not Available",
            "eligibility": "Not Available"
        })
        course_id += 1

    university_id += 1

# Create DataFrames
df_univ = pd.DataFrame(universities)
df_courses = pd.DataFrame(courses)

df_univ

# Export to Excel

with pd.ExcelWriter("university_data.xlsx", engine="openpyxl") as writer:
    df_univ.to_excel(writer, sheet_name="Universities", index=False)
    df_courses.to_excel(writer, sheet_name="Courses", index=False)

print("Excel file created successfully!")

print("Universities Count:", len(df_univ))
print("Courses Count:", len(df_courses))

print("\nDuplicate Universities:", df_univ.duplicated().sum())
