def scrape_university(univ_name, country, city, website, course_page):
    global university_id_counter
    global course_id_counter

    universities.append({
        "university_id": university_id_counter,
        "university_name": univ_name,
        "country": country,
        "city": city,
        "website": website
    })

    try:
        response = requests.get(course_page)
        response.raise_for_status()
        soup = BeautifulSoup(response.text, "html.parser")

        course_elements = soup.find_all("a")

        count = 0
        for course in course_elements:
            course_name = course.text.strip()

            if len(course_name) > 5 and count < 5:
                courses.append({
                    "course_id": course_id_counter,
                    "university_id": university_id_counter,
                    "course_name": course_name,
                    "level": "Not Available",
                    "discipline": "Not Available",
                    "duration": "Not Available",
                    "fees": "Not Available",
                    "eligibility": "Not Available"
                })

                course_id_counter += 1
                count += 1

    except Exception as e:
        print(f"Error scraping {univ_name}: {e}")

    university_id_counter += 1

